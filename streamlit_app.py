def create_logo():
    """
    Creates the Nile Harvest Foods logo as a PNG in memory.

    The image is generated by Python so Streamlit does not
    depend on an external logo file or HTML/CSS rendering.
    """

    try:
        from PIL import Image, ImageDraw

        size = 420

        image = Image.new(
            "RGBA",
            (size, size),
            (0, 0, 0, 0),
        )

        draw = ImageDraw.Draw(image)

        # ----------------------------------------------------
        # Main rounded square
        # ----------------------------------------------------

        draw.rounded_rectangle(
            (15, 15, size - 15, size - 15),
            radius=85,
            fill=(30, 100, 55, 255),
        )

        # ----------------------------------------------------
        # Inner green area
        # ----------------------------------------------------

        draw.rounded_rectangle(
            (30, 30, size - 30, size - 30),
            radius=70,
            fill=(46, 125, 50, 255),
        )

        # ----------------------------------------------------
        # Gold sunrise
        # ----------------------------------------------------

        draw.ellipse(
            (135, 70, 285, 220),
            fill=(242, 190, 45, 255),
        )

        # ----------------------------------------------------
        # Soil
        # ----------------------------------------------------

        draw.rounded_rectangle(
            (30, 285, size - 30, size - 30),
            radius=60,
            fill=(91, 62, 45, 255),
        )

        # ----------------------------------------------------
        # Plant stem
        # ----------------------------------------------------

        draw.rounded_rectangle(
            (202, 145, 218, 310),
            radius=8,
            fill=(174, 213, 129, 255),
        )

        # ----------------------------------------------------
        # Left leaf
        # ----------------------------------------------------

        draw.ellipse(
            (95, 145, 215, 230),
            fill=(129, 199, 132, 255),
        )

        # ----------------------------------------------------
        # Right leaf
        # ----------------------------------------------------

        draw.ellipse(
            (205, 145, 325, 230),
            fill=(129, 199, 132, 255),
        )

        # ----------------------------------------------------
        # Leaf veins
        # ----------------------------------------------------

        draw.line(
            (155, 190, 205, 230),
            fill=(46, 125, 50, 255),
            width=6,
        )

        draw.line(
            (265, 190, 215, 230),
            fill=(46, 125, 50, 255),
            width=6,
        )

        # ----------------------------------------------------
        # Small gold grain symbols
        # ----------------------------------------------------

        for x, y in [
            (95, 315),
            (125, 300),
            (155, 320),
            (265, 320),
            (295, 300),
            (325, 315),
        ]:
            draw.ellipse(
                (x, y, x + 18, y + 30),
                fill=(242, 190, 45, 255),
            )

        # ----------------------------------------------------
        # Convert to PNG
        # ----------------------------------------------------

        buffer = io.BytesIO()

        image.save(
            buffer,
            format="PNG",
        )

        buffer.seek(0)

        return buffer

    except Exception as exc:
        logging.exception(
            "Unable to generate Nile Harvest logo: %s",
            exc,
        )
        return None


